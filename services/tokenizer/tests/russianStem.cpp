TEST(StemmerTestSuite, RussianLang) {
	setlocale(LC_ALL, "");
  RussianStemAction stemmer;
  for (size_t i = 0; i < tests.size(); ++i) {
    std::wstring given = tests[i].first, expected = tests[i].second;
    std::wcerr << i << L") " << given << ' ' << expected << '\n';
    stemmer(given);
    std::wstring result = given;
    std::wcerr << i << L") " << result << ' ' << expected << '\n';

    EXPECT_EQ(result, expected);
  }
}
